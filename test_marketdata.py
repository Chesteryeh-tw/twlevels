# -*- coding: utf-8 -*-
"""marketidx.py、qfii.py 的解析測試。樣本是 2026-10-08 證交所實際回傳的欄位格式。"""
import marketidx as M
import qfii as Q

TAIEX = {"stat": "OK", "fields": ["日期", "開盤指數", "最高指數", "最低指數", "收盤指數"],
         "data": [["115/10/01", "47,961.98", "48,353.49", "47,893.42", "48,353.49"],
                  ["115/10/08", "49,783.06", "49,783.06", "49,189.77", "49,313.44"]]}

QF = {"stat": "OK", "fields": ["證券代號", "證券名稱", "國際證券編碼", "發行股數",
      "外資及陸資尚可投資股數", "全體外資及陸資持有股數", "外資及陸資尚可投資比率",
      "全體外資及陸資持股比率", "外資及陸資共用法令投資上限比率", "陸資法令投資上限比率",
      "與前日異動原因(註)", "最近一次上市公司申報外資及陸資持股異動日期"],
      "data": [["00400A", "主動國泰動能高息", "TW00000400A3", "1,897,140,000", "1,863,549,403",
                "33,590,597", "98.22", "1.77", "100.00", "100.00", "", "115/04/10"],
               ["1101", "台泥", "TW0001101004", "7,523,181,000", "5,000,000,000",
                "2,123,456,789", "66.66", "28.22", "100.00", "100.00", "", "115/09/30"]]}

def test_taiex():
    m = M.parse_month(TAIEX)
    assert m["20261008"] == (49783.06, 49783.06, 49189.77, 49313.44)
    assert len(m) == 2
    assert M.parse_month({"stat": "很抱歉"}) == {}

def test_qfii():
    r = Q.parse(QF)
    assert r == [("1101", 28.22, 2123457)]     # ETF（6 碼）不收；股數換張
    assert Q.parse(None) == []

if __name__ == "__main__":
    test_taiex(); test_qfii(); print("ok")
